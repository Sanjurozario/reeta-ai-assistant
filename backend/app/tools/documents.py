import os
import time
from pathlib import Path
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from app.config import settings
from app.permissions.policy import ActionTier
from app.tools.registry import BaseTool, VerificationResult


class SectionItem(BaseModel):
    heading: str
    body: str


class PdfReportInput(BaseModel):
    title: str = Field(..., description="Report Title")
    sections: List[SectionItem] = Field(..., description="List of report sections with heading and body text")
    filename: Optional[str] = Field(default=None, description="Output filename (e.g. 'crm_pricing.pdf')")
    author: Optional[str] = Field(default="REETA Autonomous Agent", description="Author name")


class PdfReportTool(BaseTool):
    name = "create_pdf_report"
    description = "Generates a styled, multi-section PDF document report using ReportLab with empirical disk validation."
    category = "documents"
    args_schema = PdfReportInput
    default_tier = ActionTier.AUTONOMOUS
    timeout_seconds = 30.0

    async def execute(
        self,
        title: str,
        sections: List[Dict[str, str]],
        filename: Optional[str] = None,
        author: Optional[str] = "REETA Autonomous Agent",
    ) -> Dict[str, Any]:
        from reportlab.lib.pagesizes import letter
        from reportlab.lib import colors
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

        reports_dir = Path(settings.AUTHORIZED_WORKSPACE) / "reports"
        reports_dir.mkdir(parents=True, exist_ok=True)

        if not filename:
            safe_title = "".join(c for c in title if c.isalnum() or c in (" ", "_", "-")).rstrip()
            filename = f"{safe_title.replace(' ', '_').lower()}_{int(time.time())}.pdf"

        if not filename.endswith(".pdf"):
            filename += ".pdf"

        target_path = reports_dir / filename

        doc = SimpleDocTemplate(
            str(target_path),
            pagesize=letter,
            rightMargin=54,
            leftMargin=54,
            topMargin=54,
            bottomMargin=54,
        )

        styles = getSampleStyleSheet()

        # Custom REETA Palette Styles
        title_style = ParagraphStyle(
            "ReetaTitle",
            parent=styles["Heading1"],
            fontName="Helvetica-Bold",
            fontSize=24,
            leading=28,
            textColor=colors.HexColor("#0F172A"),
            spaceAfter=8,
        )

        meta_style = ParagraphStyle(
            "ReetaMeta",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#64748B"),
            spaceAfter=15,
        )

        h2_style = ParagraphStyle(
            "ReetaH2",
            parent=styles["Heading2"],
            fontName="Helvetica-Bold",
            fontSize=14,
            leading=18,
            textColor=colors.HexColor("#0891B2"),
            spaceBefore=14,
            spaceAfter=6,
        )

        body_style = ParagraphStyle(
            "ReetaBody",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=10,
            leading=15,
            textColor=colors.HexColor("#334155"),
            spaceAfter=8,
        )

        story = []

        # Document Header
        story.append(Paragraph(title, title_style))
        created_str = time.strftime("%Y-%m-%d %H:%M:%S UTC", time.gmtime())
        story.append(Paragraph(f"Generated by: {author} | Date: {created_str}", meta_style))
        story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#0891B2"), spaceAfter=15))

        # Sections
        for sec in sections:
            heading = sec.get("heading", "") if isinstance(sec, dict) else sec.heading
            body = sec.get("body", "") if isinstance(sec, dict) else sec.body

            if heading:
                story.append(Paragraph(heading, h2_style))
            if body:
                # Replace newlines with breaks
                formatted_body = body.replace("\n", "<br/>")
                story.append(Paragraph(formatted_body, body_style))
            story.append(Spacer(1, 10))

        # Build Document
        doc.build(story)

        size = target_path.stat().st_size
        return {
            "status": "success",
            "pdf_path": str(target_path),
            "size_bytes": size,
            "title": title,
            "filename": filename,
        }

    async def verify_outcome(self, result: Any, **kwargs) -> VerificationResult:
        if not isinstance(result, dict) or "pdf_path" not in result:
            return VerificationResult(verified=False, evidence="PDF generation did not return file path.")

        path = Path(result["pdf_path"])
        if not path.exists():
            return VerificationResult(verified=False, evidence=f"File not found on disk: {path}")

        size = path.stat().st_size
        if size == 0:
            return VerificationResult(verified=False, evidence="Generated PDF file is empty (0 bytes).")

        # Verify PDF magic byte header (%PDF-)
        with open(path, "rb") as f:
            header = f.read(5)
            if header != b"%PDF-":
                return VerificationResult(verified=False, evidence=f"File at {path} does not have valid PDF magic header.")

        return VerificationResult(
            verified=True,
            evidence=f"Empirically validated PDF report generated at {path.name} ({size} bytes) with valid PDF-1.x binary header.",
            details={"path": str(path), "size": size},
        )

